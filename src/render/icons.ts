const cache = new Map<string, HTMLCanvasElement>()

function render(rows: string[]): HTMLCanvasElement {
  const h = rows.length
  const w = rows[0].length
  const c = document.createElement('canvas')
  c.width = w
  c.height = h
  const g = c.getContext('2d')!
  g.imageSmoothingEnabled = false
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const col = C[rows[y][x]]
      if (!col) continue
      g.fillStyle = col
      g.fillRect(x, y, 1, 1)
    }
  }
  return c
}

/** キー（例: 'building:tank'）に対応するドット絵。無ければ null */
export function pixelIcon(key: string): HTMLCanvasElement | null {
  const hit = cache.get(key)
  if (hit) return hit
  const rows = ICONS[key] ?? TARGETS[key]
  if (!rows) return null
  const c = render(rows)
  cache.set(key, c)
  return c
}

export function hasPixelIcon(key: string): boolean {
  return key in ICONS || key in TARGETS
}
